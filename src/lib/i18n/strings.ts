export const STRINGS: Partial<Record<Locale, Record<StringKey, string>>> = { en: EN, es: ES, "zh-Hant": ZH_HANT, "zh-Hans": ZH_HANS, vi: VI, tl: TL, ko: KO };
export const EN_STRINGS: Record<StringKey, string> = EN;
export const STRING_KEYS = Object.keys(EN) as StringKey[];

/**
 * Resolve a UI string. `live` is an optional map of English text to a live
 * translation (for locales without a dictionary); the English text is the
 * last resort.
 */
export function translate(locale: Locale, key: StringKey, vars?: Record<string, string | number>, live?: Record<string, string>): string {
  let s = STRINGS[locale]?.[key] ?? live?.[EN[key]] ?? EN[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
