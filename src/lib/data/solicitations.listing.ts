/**
 * Listing-only records from other Alameda County agencies, captured from their
 * public posting pages on 2026-10-03. Only what the listing showed (title,
 * number, due date, link) is recorded; requirements were NOT read, so these
 * records carry `listingOnly: true` and the engine never rates them above
 * "possible fit". They show how a centralized feed across agencies looks.
 */
import type { Category, SolicitationInput } from "./types";

interface ListingSpec {
  id: string;
  agencyId: string;
  number: string;
  title: string;
  department: string;
  type: SolicitationInput["type"];
  category: Category;
  secondary?: Category[];
  summary: string;
  due: { date: string; time?: string } | null;
  posted: string;
  url: string;
  listingUrl: string;
  excerpt: string;
  scopeTags?: SolicitationInput["scopeTags"];
  contact?: { name: string; email: string; phone?: string };
}

function listing(s: ListingSpec): SolicitationInput {
  return {
    id: s.id,
    number: s.number,
    title: s.title,
    department: s.department,
    agencyId: s.agencyId,
    type: s.type,
    category: s.category,
    secondaryCategories: s.secondary ?? [],
    summary: s.summary,
    description: `${s.summary} Only the public listing has been captured so far; open the posting to read the requirements, documents and submission instructions.`,
    estimatedValue: null,
    dates: {
      posted: s.posted,
      // Rolling / unknown due dates are represented as far-future so they stay "open" without appearing in Closing Soon.
      submissionDue: s.due ?? { date: "2027-12-31", note: "No due date shown on the listing (rolling or not yet posted)" },
    },
    submissionMethod: "See the posting for submission instructions.",
    requirements: {
      licenses: [],
      certifications: [],
      insurance: [],
      location: { type: "none" },
      bonding: [],
      prevailingWage: false,
      livingWage: false,
      dirRegistration: false,
      other: [],
    },
    documents: [],
    scopeTags: s.scopeTags ?? [],
    contact: s.contact ?? { name: "See posting", email: "" },
    sourceUrl: s.url,
    sourceExcerpt: `${s.excerpt}\nListing captured from ${s.listingUrl} on October 3, 2026.`,
    status: "open",
    listingOnly: true,
    provenance: {
      source: "portal",
      extractedBy: "human",
      extractedAt: "2026-10-03",
      note: "Listing only. Title, number, due date and link were read from the agency's posting page; requirements have not been extracted.",
    },
  };
}

